#!/usr/bin/env python3
"""Sony PsyQ ranges of the SLUS-00726 main executable, and the port check.

`build` derives config/psyq_ranges.txt (vram ranges and segment names only)
from the vendor splat layout (vendor/bfm-decomp/config/splat.us.exe.yaml):
code subsegments named snd*, lib*, apicard* or gap are Sony library code.
The table also includes independently identified SDK routines in layout gaps.

`check` fails when a decomp source whose vram lies in a PsyQ range is
compiled into a port target. The port gets PsyQ behaviour from PsyCross
(MIT) or our own HLE, never from SDK objects or decompiled PsyQ C.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "config/psyq_ranges.txt"
EXE_TEXT, EXE_BASE = 0x800, 0x80010000
PSYQ = re.compile(r"^(snd|lib|apicard|gap$)")


def build(splat):
    segs = []
    for m in re.finditer(r"^\s*- \[(0x[0-9A-Fa-f]+), (\w+|\.\w+), (\w+)\]", splat.read_text(), re.M):
        segs.append((int(m.group(1), 16), m.group(2), m.group(3)))
    end_marker = re.search(r"^\s*- \[(0x[0-9A-Fa-f]+)\]\s*$", splat.read_text(), re.M)
    rows = []
    for i, (off, kind, name) in enumerate(segs):
        if kind != "c":
            continue
        nxt = segs[i + 1][0] if i + 1 < len(segs) else int(end_marker.group(1), 16)
        if PSYQ.match(name):
            rows.append((off - EXE_TEXT + EXE_BASE, nxt - EXE_TEXT + EXE_BASE, name))
    # These complete sound-library routines occupy gaps in the historical layout.
    identified = (
        (0x8003C438, 0x8003C498, "libspu_transfer"),
        (0x8003D424, 0x8003D434, "libspu_reverb"),
        (0x8003D630, 0x8003D650, "libsnd_quit"),
        (0x8003DC90, 0x8003E248, "libsnd_crescendo"),
        (0x8003E2E4, 0x8003E310, "libsnd_play"),
        (0x8003FA54, 0x8003FA64, "libsnd_vm_doff"),
        (0x80040DE8, 0x800414E4, "libsnd_vm_seq"),
    )
    for lo, hi, name in identified:
        if not any(start <= lo and hi <= end for start, end, _ in rows):
            rows.append((lo, hi, name))
    rows.sort()
    if any(left[1] > right[0] for left, right in zip(rows, rows[1:])):
        raise ValueError("overlapping SDK ranges")
    lines = ["# Sony PsyQ code in the SLUS-00726 main executable: <start> <end> <segment>.",
             "# Generated by tools/psyq_manifest.py build from the layout and identified SDK routines.",
             "# Addresses and names only."]
    lines += [f"{lo:08x} {hi:08x} {name}" for lo, hi, name in rows]
    MANIFEST.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} PsyQ ranges, {sum(h - l for l, h, _ in rows)} bytes")


def ranges():
    out = []
    for line in MANIFEST.read_text().splitlines():
        if line and not line.startswith("#"):
            lo, hi, name = line.split()
            out.append((int(lo, 16), int(hi, 16), name))
    return out


def psyq_segment(vram, table=None):
    for lo, hi, name in table or ranges():
        if lo <= vram < hi:
            return name
    return None


# MAIN.CD overlays reuse virtual addresses. These intervals belong only to the
# named member. The word between them is outside both routines.
SDK_OVERLAY_RANGES = (
    ("main_0003", 0x800D2AA0, 0x800D3200, "libpress"),
    ("main_0003", 0x800D3204, 0x800D3574, "libpress"),
)


def sdk_overlay(region, pc, size=1):
    """Identify an SDK interval intersecting a source extent in this member."""
    for member, start, end, library in SDK_OVERLAY_RANGES:
        if member == region and pc < end and start < pc + size:
            return library
    return None


def source_vram(path):
    m = re.match(r"([0-9a-fA-F]{8})", Path(path).name)
    if not m or "src/main/" not in str(path).replace("\\", "/"):
        return None
    return int(m.group(1), 16)


def source_segment(path, table):
    path = str(path).replace("\\", "/")
    overlay = re.search(r"(?:^|[/:])src/overlays/([^/]+)/([0-9a-fA-F]{8})[^/]*$", path)
    if overlay:
        return sdk_overlay(overlay[1], int(overlay[2], 16))
    vram = source_vram(path)
    return psyq_segment(vram, table) if vram is not None else None


def check(sources, allow):
    table = ranges()
    allowed = set()
    if allow and Path(allow).is_file():
        allowed = {l.split()[0] for l in Path(allow).read_text().splitlines()
                   if l.strip() and not l.startswith("#")}
    bad, pending = [], []
    for src in sources:
        seg = source_segment(src, table)
        if seg:
            rel = str(Path(src).resolve().relative_to(ROOT)) if Path(src).is_absolute() else src
            (pending if rel in allowed else bad).append((rel, seg))
    for rel, seg in pending:
        print(f"psyq-check: PENDING replacement {rel} (PsyQ {seg})", file=sys.stderr)
    for rel, seg in bad:
        print(f"psyq-check: FORBIDDEN {rel} is Sony PsyQ code ({seg}); use PsyCross/HLE", file=sys.stderr)
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--splat", type=Path,
                   default=ROOT / "vendor/bfm-decomp/config/splat.us.exe.yaml")
    c = sub.add_parser("check")
    c.add_argument("--allow", help="file of repo-relative sources pending replacement")
    c.add_argument("sources", nargs="*")
    args = ap.parse_args()
    if args.cmd == "build":
        build(args.splat)
        return 0
    return check(args.sources, args.allow)


if __name__ == "__main__":
    sys.exit(main())
